def write_csv(path,rows,fields):
    with Path(path).open('x',newline='') as f:
        w=csv.DictWriter(f,fieldnames=fields,extrasaction='ignore');w.writeheader()
        for r in rows:w.writerow({k:json.dumps(v,sort_keys=True) if isinstance(v,(dict,list)) else v for k,v in r.items()})


def policies_from_config(config):
    policies={}
    for spec in config['policies']:
        p=VWAPAnchorPolicy(**spec)
        if p.symbol in policies:raise ResearchError('DUPLICATE_ANCHOR_SYMBOL')
        if p.symbol not in MARKETS:raise ResearchError('UNKNOWN_ANCHOR_SYMBOL')
        policies[p.symbol]=p
    return policies


def anchor_observations(observations,policies):
    """Evaluate only saved decision moments, never retroactive old candle entries.

    Historical candles fetched at noon do not establish a 09:00 candidate's
    availability. The record must prove every constituent candle was received by
    the saved scan time. No fill or position is generated by this evaluator.
    """
    results=[];seen=set()
    for o in observations:
        symbol=o['symbol'];t=stamp(o['scan_observed_at_ms']);identity=(symbol,t)
        if identity in seen:raise ResearchError('DUPLICATE_ANCHOR_OBSERVATION')
        if symbol not in MARKETS:raise ResearchError('UNKNOWN_MARKET')
        seen.add(identity)
        for arm in ('UTC_NO_ML','SESSION_NO_ML'):
            p=VWAP_BASELINE_UTC if arm=='UTC_NO_ML' else policies.get(symbol,VWAP_BASELINE_UTC)
            result=dict(experiment=arm,symbol=symbol,decision_ms=t,utc_day=utc_day(t),policy_id=p.policy_id,
                policy_configured=arm=='UTC_NO_ML' or symbol in policies,signal_count=0,long_signals=0,short_signals=0,
                accepted_trades=None,win_rate=None,average_win=None,average_loss=None,expectancy=None,
                gross_pnl=None,fees=None,funding_cost=None,slippage=None,net_pnl=None,max_drawdown=None,
                daily_equity_volatility=None,time_in_market=None,status='INCONCLUSIVE',reason=None,
                source='SAVED_PUBLIC_CANDLE_DECISION_MOMENT',regime=[],execution_capability=False)
            try:
                cs=o['candles']
                if not cs:raise ResearchError('NO_CANDLES')
                if any(c.get('symbol')!=symbol for c in cs):raise ResearchError('CANDLE_SYMBOL_MISMATCH')
                for c in cs:
                    end=stamp(c['close_timestamp_ms']);received=stamp(c.get('received_timestamp_ms'))
                    if end not in {c['timestamp_ms']+59999,c['timestamp_ms']+60000} or not end<=received<=t:
                        raise ResearchError('CANDLE_AVAILABILITY_OR_BOUNDARY_UNPROVEN')
                frame=pd.DataFrame(dict(Timestamp=pd.to_datetime([c['timestamp_ms'] for c in cs],unit='ms',utc=True),
                    Open=[float(c['open']) for c in cs],High=[float(c['high']) for c in cs],Low=[float(c['low']) for c in cs],
                    Close=[float(c['close']) for c in cs],Volume=[float(c['volume']) for c in cs]))
                validate_frame(frame,t);brain=AnchorResearchBrain(p);enriched=brain.evaluate_frame(frame,t);last=enriched.iloc[-1]
                result.update(vwap=float(last.VWAP) if math.isfinite(last.VWAP) else None,
                    atr=float(last.ATR_14),ema9=float(last.EMA_9),ema21=float(last.EMA_21),
                    last_candle_ms=cs[-1]['timestamp_ms'],anchor_coverage_complete=brain.coverage_complete(frame))
                if t-(cs[-1]['timestamp_ms']+60000)>120000:raise ResearchError('STALE_COMPLETED_CANDLE')
                if not brain.coverage_complete(frame):raise ResearchError('TRUNCATED_ANCHOR_HISTORY')
                if arm=='SESSION_NO_ML' and symbol not in policies:raise ResearchError('SESSION_POLICY_NOT_CONFIGURED')
                setup=last.get('Signal_Type');direction=SETUPS.get(setup)
                result.update(signal_count=int(direction is not None),long_signals=int(direction=='LONG'),
                    short_signals=int(direction=='SHORT'),status='SIGNAL_OBSERVATION_ONLY',reason='NO_EXECUTABLE_QUOTE_AND_PORTFOLIO_PATH',
                    setup_type=setup if direction else None)
                from .dataset import regime
                close=float(last.Close)
                result['regime']=regime(dict(atr_fraction=float(last.ATR_14)/close,ema_separation_fraction=(float(last.EMA_9)-float(last.EMA_21))/close))
            except (ResearchError,ValueError,KeyError,TypeError) as exc:result['reason']=str(exc)
            results.append(result)
    return results


def data_gate(quality,defaults):
    checks={'candidate_rows':quality['usable_labeled_rows']>=defaults['minimum_labeled_candidates'],
            'dates':len(quality['labeled_dates'])>=defaults['minimum_labeled_dates'],
            'markets':len(quality['labeled_markets'])>=defaults['minimum_labeled_markets'],
            'positives':quality['positive_outcomes']>=defaults['minimum_positive_outcomes'],
            'negatives':quality['negative_outcomes']>=defaults['minimum_negative_outcomes'],
            'both_directions':all(quality['directions'].get(s,0)>=defaults['minimum_per_direction'] for s in ('LONG','SHORT'))}
    return dict(status='ELIGIBLE_FOR_RESEARCH_FIT' if all(checks.values()) else 'INSUFFICIENT_DATA',checks=checks,
                note='Eligibility floor is not performance validation or production approval.')


def aggregate_anchors(results):
    """Per-market totals with explicit observational denominators and no fake P&L."""
    groups={}
    for r in results:groups.setdefault((r['experiment'],r['symbol']),[]).append(r)
    output=[]
    for (arm,symbol),rows in sorted(groups.items()):
        actual=[r for r in rows if 'decision_ms' in r]
        eligible=[r for r in actual if r['status']=='SIGNAL_OBSERVATION_ONLY']
        output.append(dict(experiment=arm,symbol=symbol,observations=len(actual),eligible_decision_observations=len(eligible),
            utc_dates=len({r['utc_day'] for r in actual}),signal_count=sum(r['signal_count'] for r in eligible),
            long_signals=sum(r['long_signals'] for r in eligible),short_signals=sum(r['short_signals'] for r in eligible),
            signal_frequency=sum(r['signal_count'] for r in eligible)/len(eligible) if eligible else None,
            accepted_trades=None,win_rate=None,average_win=None,average_loss=None,expectancy=None,gross_pnl=None,
            fees=None,funding_cost=None,slippage=None,net_pnl=None,max_drawdown=None,daily_equity_volatility=None,time_in_market=None,
            status='INCONCLUSIVE',reason=';'.join(sorted({r['reason'] for r in rows if r.get('reason')}))))
    return output


def partition_gate(p,defaults):
    for name in ('train','calibration','validation','holdout'):
        if len(p[name])<defaults['minimum_'+name]:return False
        counts=Counter(r['label'] for r in p[name])
        if any(counts.get(c,0)<defaults['minimum_class_per_partition'] for c in (0,1)):return False
    return True


def _split_for(rows,defaults):
    days=sorted({r['utc_day'] for r in rows})
    if len(days)<20:return None
    def ms(day):return int(datetime.fromisoformat(day).replace(tzinfo=timezone.utc).timestamp()*1000)
    return ChronologicalSplit(ms(days[int(len(days)*.6)]),ms(days[int(len(days)*.8)]),ms(days[int(len(days)*.7)]),defaults['default_embargo_ms'])


def run_research(*,output,registry,traces=(),candidate_observations=None,feature_observations=None,outcomes=None,
                 candle_observations=(),anchor_config=None,assumptions=None,split=None):
    output=Path(output);registry=Path(registry);identity=source_identity()
    traces=list(traces);candle_observations=list(candle_observations)
    spec=dict(source=identity,dataset_hash=digest(dict(traces=list(traces),candidates=candidate_observations,
        features=feature_observations,outcomes=outcomes,candles=list(candle_observations))),anchor_config=anchor_config,
        assumptions=assumptions or {},split=asdict(split) if split else None)
    run_id=digest(spec);event=dict(experiment_id=run_id,hypothesis='VWAP reference or candidate regime filtering improves after-cost risk-adjusted outcomes',
        variables_changed=['RESEARCH_ANCHOR_ONLY','RESEARCH_CANDIDATE_PERMISSION_ONLY'],dataset=spec['dataset_hash'],source_hash=identity['source_hash'])
    record_attempt(registry,dict(event,result='STARTED',conclusion='PRESPECIFIED_FOUR_ARM_RESEARCH'))
    try:
        if output.exists():raise ResearchError('OUTPUT_ALREADY_EXISTS_USE_NEW_RUN_DIRECTORY')
        output.mkdir(parents=True)
        for name in ('vwap_anchor','ml','comparisons','reports'):(output/name).mkdir()
        defaults=json.loads((ROOT/'research/configurations/experiment_defaults.json').read_text())
        anchors=policies_from_config(anchor_config or {'policies':[]})
        raw,ignored=from_opportunity_traces(traces,feature_observations=feature_observations) if candidate_observations is None else (list(candidate_observations),[])
        rows,quality=build_dataset(raw,outcomes,assumptions=assumptions)
        gate=data_gate(quality,defaults);eligible=[r for r in rows if r['scoring_ready'] and r['label'] is not None]
        # Each anchor experiment needs its own model/dataset. Never apply a UTC model
        # to session candidates without a separately evaluated feature distribution.
        anchors_result=anchor_observations(candle_observations,anchors)
        for n in MARKETS:
            for arm in ('UTC_NO_ML','SESSION_NO_ML'):
                if not any(r['symbol']==n and r['experiment']==arm for r in anchors_result):
                    anchors_result.append(dict(experiment=arm,symbol=n,signal_count=0,long_signals=0,short_signals=0,
                        accepted_trades=None,net_pnl=None,max_drawdown=None,daily_equity_volatility=None,status='INCONCLUSIVE',reason='NO_SAVED_DECISION_OBSERVATION'))
        immutable_json(output/'ml/feature_manifest.json',feature_manifest());immutable_json(output/'ml/data_quality.json',dict(quality,gate=gate,ignored_market_observations=ignored))
        with (output/'ml/candidate_dataset.jsonl').open('x') as f:
            for row in rows:f.write(json.dumps(row,sort_keys=True,allow_nan=False)+'\n')
        resolved_split=split or _split_for(eligible,defaults)
        split_manifest=resolved_split.manifest(eligible) if resolved_split else dict(status='INSUFFICIENT_DATA',split_candidate_ids={},holdout_used_for_tuning=False)
        immutable_json(output/'ml/split_manifest.json',split_manifest)
        model_results={};model_manifests=[];decisions=[];calibration=[];importance=[]
        for policy_id in sorted({r['anchor_policy_id'] for r in eligible}):
            group=[r for r in eligible if r['anchor_policy_id']==policy_id]
            _,q=build_dataset([x for x in raw if x['anchor_policy_id']==policy_id],outcomes,assumptions=assumptions)
            if data_gate(q,defaults)['status']!='ELIGIBLE_FOR_RESEARCH_FIT' or resolved_split is None:continue
            parts=resolved_split.partition(group)
            if not partition_gate(parts,defaults):continue
            models=train_models(parts,digest(feature_manifest()),identity['source_hash'],spec['dataset_hash'])
            # Immutable weights/calibration/threshold are written BEFORE holdout scoring.
            for model in models:
                filename=model['model_version']+'.json';save_model(output/'ml'/filename,model)
            HoldoutLedger(registry.parent/'holdout_seals').claim(dict(dataset_hash=spec['dataset_hash'],policy=policy_id,
                ids=[r['candidate_id'] for r in parts['holdout']],split=split_manifest['sha256']),
                dict(spec=spec,model_versions=[m['model_version'] for m in models]))
            for model in models:
                version=model['model_version'];controller=MetaController(model,feature_hash=digest(feature_manifest()))
                evaluated={k:evaluate_model(parts[k],model) for k in ('train','validation','holdout')}
                evaluated['train']['evaluation_scope']='IN_SAMPLE_DO_NOT_PRESENT_AS_HOLDOUT'
                evaluated['validation']['evaluation_scope']='THRESHOLD_SELECTION_DATA_NOT_UNTOUCHED'
                evaluated['holdout']['evaluation_scope']='UNTOUCHED_AFTER_MODEL_THRESHOLD_SEALED'
                evaluated['model_type']=model['model_type'];evaluated['anchor_policy_id']=policy_id
                model_results[version]=evaluated
                model_manifests.append(dict(model_version=version,model_type=model['model_type'],anchor_policy_id=policy_id,
                    path=filename,state='RESEARCH',threshold=model['threshold'],created_utc=datetime.now(timezone.utc).isoformat(),
                    source_hash=identity['source_hash'],dataset_hash=spec['dataset_hash'],feature_manifest_hash=digest(feature_manifest()),
                    intervals=asdict(resolved_split),holdout_used_for_tuning=False))
                for row in parts['holdout']:decisions.append(controller.score(row))
                for segment in ('train','validation','holdout'):
                    calibration.extend(dict(model_version=version,segment=segment,**b) for b in evaluated[segment]['classification']['calibration'])
                importance.extend(dict(model_version=version,**i) for i in model_importance(model))
        trained=bool(model_results)
        unavailable=MetaController()
        if not trained:decisions=[unavailable.score(r) for r in rows]
        # Honest no-ML/heuristic controls use the SAME candidate outcomes/costs.
        controls={}
        for policy in sorted({r['anchor_policy_id'] for r in eligible}):
            group=[r for r in eligible if r['anchor_policy_id']==policy]
            segments=resolved_split.partition(group) if resolved_split else {'unpartitioned':group}
            controls[policy]=dict(segments={name:dict(NO_ML=performance(segment),
                HEURISTIC=performance([r for r in segment if r['features']['spread_bps']<=15 and r['features']['atr_fraction']>=.004]))
                for name,segment in segments.items() if name!='purged'},
                explanation='Prespecified measured ATR/spread heuristic; no probability claim; research only')
        immutable_json(output/'ml/model_manifest.json',dict(status='RESEARCH_MODELS_FITTED_NOT_PROMOTED' if trained else 'INSUFFICIENT_DATA',models=model_manifests,
            lifecycle_states=['RESEARCH','VALIDATED','PROMOTION_CANDIDATE','REJECTED','RETIRED'],production_transition=False))
        immutable_json(output/'ml/model_metrics.json',dict(status='RESEARCH_ONLY' if trained else 'INSUFFICIENT_DATA',models=model_results,controls=controls))
        with (output/'ml/candidate_explanations.jsonl').open('x') as f:
            for row in decisions:f.write(json.dumps(row,sort_keys=True,allow_nan=False)+'\n')
        write_csv(output/'ml/calibration.csv',calibration,['model_version','segment','lower','upper','count','mean_probability','observed_positive_fraction'])
        write_csv(output/'ml/feature_importance.csv',importance,['model_version','feature','importance','method'])
        fields=['experiment','symbol','policy_id','decision_ms','signal_count','long_signals','short_signals','accepted_trades','win_rate','average_win','average_loss',
            'expectancy','gross_pnl','fees','funding_cost','slippage','net_pnl','max_drawdown','daily_equity_volatility','time_in_market','status','reason']
        write_csv(output/'vwap_anchor/anchor_results.csv',anchors_result,fields)
        write_csv(output/'vwap_anchor/market_results.csv',aggregate_anchors(anchors_result),
            fields+['observations','eligible_decision_observations','utc_dates','signal_frequency'])
        regime_rows=[dict(r,regime=g) for r in anchors_result for g in r.get('regime',[])];write_csv(output/'vwap_anchor/regime_results.csv',regime_rows,['regime']+fields)
        matrix=[]
        for arm,policy,ml in [('UTC_NO_ML','VWAP_BASELINE_UTC',False),('SESSION_NO_ML','SESSION_AWARE',False),('UTC_ML','VWAP_BASELINE_UTC',True),('SESSION_ML','SESSION_AWARE',True)]:
            models=[(k,m) for k,m in model_results.items() if (m['anchor_policy_id']=='VWAP_BASELINE_UTC')==(policy=='VWAP_BASELINE_UTC')]
            matched=[r for r in eligible if (r['anchor_policy_id']=='VWAP_BASELINE_UTC')==(policy=='VWAP_BASELINE_UTC')]
            conditional=performance(matched) if not ml else None
            matrix.append(dict(experiment=arm,anchor=policy,ml=ml,net_pnl=None,max_drawdown=None,daily_equity_volatility=None,
                accepted_trades=None,expectancy=None,status='INCONCLUSIVE',
                reason='CONDITIONAL_MODEL_RESULTS_AVAILABLE_NO_ALTERNATE_PORTFOLIO_REPLAY' if ml and models else 'INSUFFICIENT_CANDIDATE_OUTCOMES_AND_FULL_PORTFOLIO_REPLAY',
                model_versions=[k for k,_ in models],assumptions_hash=digest(assumptions or {}),
                conditional_recorded_outcomes=conditional,
                conditional_holdout_model_results={k:m['holdout']['conditional_trading'] for k,m in models} if ml else {}))
        for filename in ('full_experiment_matrix.csv','baseline_vs_anchor.csv','baseline_vs_ml.csv'):
            subset=matrix if filename=='full_experiment_matrix.csv' else [matrix[0],matrix[1 if filename=='baseline_vs_anchor.csv' else 2]]
            write_csv(output/'comparisons'/filename,subset,['experiment','anchor','ml','net_pnl','max_drawdown','daily_equity_volatility','accepted_trades','expectancy','status','reason','model_versions','assumptions_hash','conditional_recorded_outcomes','conditional_holdout_model_results'])
        status=dict(BASELINE_PRESERVED=True,VWAP_RESEARCH_READY=True,SESSION_ANCHOR_VALIDATED=False,
            ML_DATA_READY=gate['status']=='ELIGIBLE_FOR_RESEARCH_FIT',ML_MODEL_VALIDATED=False,HOLDOUT_COMPLETE=trained,
            PROMOTION_RECOMMENDED=False,PRODUCTION_CHANGED=False)
        conclusion='MORE_DATA_REQUIRED' if not trained else 'INCONCLUSIVE'
        manifest=dict(experiment_id=run_id,**spec,defaults=defaults,feature_manifest_hash=digest(feature_manifest()),
            resolved_split=asdict(resolved_split) if resolved_split else None,anchor_policies={s:p.report() for s,p in anchors.items()},
            risk_execution_cost_policy='Unchanged recorded assumptions; no new execution model or price inference',
            output_provenance='OFFLINE_RESEARCH_FROM_SAVED_EVIDENCE',exchange_orders_submitted=0,order_capability=False,
            matrix=matrix,recommendation=conclusion,status=status,quality=quality)
        immutable_json(output/'experiment_manifest.json',manifest)
        with (output/'vwap_anchor/experiments.jsonl').open('x') as f:
            for m in matrix:f.write(json.dumps(dict(experiment_id=run_id,**m),sort_keys=True)+'\n')
        for file,title,body in [
            ('vwap_anchor_report.md','VWAP anchor research',f"{len(candle_observations)} saved decision observations. UTC baseline versus documented daily reference policies. Result: INCONCLUSIVE. Only VWAP and its slope vary; EMA, ATR, volume, warmup, management and production source stay fixed. No automatic midnight/session exit or fabricated fill. Partial anchor coverage and stale data are explicitly rejected."),
            ('ml_meta_controller_report.md','Candidate-quality ML',f"{quality['candidate_rows']} valid candidate rows; {quality['usable_labeled_rows']} usable labeled rows, {quality['positive_outcomes']} positives and {quality['negative_outcomes']} negatives. Fit gate: {gate['status']}. Models fitted: {len(model_results)}. Train-only preprocessing, earlier-validation calibration, later-validation threshold choice and purged holdout. Direction comes from the deterministic candidate. Missing required input/model means ML_UNAVAILABLE. Conditional outcome subsets do not establish alternative portfolio performance."),
            ('competition_research_summary.md','Competition research evidence',f"Recommendation: {conclusion}. Production changed: FALSE. Numerical, explainable regime filtering and isolated anchor hypotheses are implemented. This run provides no scientifically validated session-anchor or ML improvement. Full four-arm portfolio comparisons, multi-regime paper outcomes and untouched holdout performance are required before a promotion proposal.")]:
            (output/'reports'/file).write_text('# '+title+'\n\n'+body+'\n\n'+json.dumps(status,indent=2)+'\n')
        record_attempt(registry,dict(event,result='COMPLETED',conclusion=conclusion,accepted_rejected_inconclusive='INCONCLUSIVE',output=str(output.resolve())))
        for arm in matrix:record_attempt(registry,dict(event,arm=arm['experiment'],result=arm['status'],conclusion=arm['reason'],accepted_rejected_inconclusive='INCONCLUSIVE'))
        return manifest
    except Exception as exc:
        record_attempt(registry,dict(event,result='FAILED',conclusion=type(exc).__name__+': '+str(exc),accepted_rejected_inconclusive='REJECTED',output=str(output.resolve())))
        raise
